def text(p):return ''.join(p.xpath('.//w:t/text()',namespaces=NS))
def digest(payload):return hashlib.sha256(payload).hexdigest()
def numbers(s):return Counter(re.findall(r'\d+(?:[,.]\d+)*',s))
def latin(s):return Counter(re.findall(r'[A-Za-z][A-Za-z0-9_./\-]*',s))
def refs(s):return re.findall(r'\[[\d,，、\-–]+\]',s)

def replace_span(p,start,end,replacement):
    nodes=p.xpath('.//w:t',namespaces=NS);position=0;inserted=False
    for node in nodes:
        value=node.text or '';left=position;right=left+len(value);position=right
        if end<=left or start>=right:continue
        a=max(0,start-left);b=min(len(value),end-left)
        node.text=value[:a]+(replacement if not inserted else '')+value[b:];inserted=True
        node.set('{http://www.w3.org/XML/1998/namespace}space','preserve')
    if not inserted:raise AssertionError('empty replacement span')

def slice_paragraph(p,start,end):
    q=deepcopy(p);position=0
    for node in q.xpath('.//w:t',namespaces=NS):
        value=node.text or '';left=position;right=left+len(value);position=right
        a=max(start,left);b=min(end,right);node.text=value[a-left:b-left] if a<b else ''
    return q

