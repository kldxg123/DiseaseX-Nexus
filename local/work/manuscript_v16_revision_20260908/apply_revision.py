def split_run_token(para_xml, token, label):
    for rm in re.finditer(r'<w:r\b[^>]*>(?:(?!</w:r>).)*?</w:r>', para_xml, re.S):
        run = rm.group(0)
        tm = re.search(r'(<w:t[^>]*>)((?:(?!</w:t>).)*)(</w:t>)', run, re.S)
        if not tm:
            continue
        text = tm.group(2)
        idx = text.find(token)
        if idx < 0:
            continue
        before, after = text[:idx], text[idx + len(token):]
        rpr_m = re.search(r'<w:rPr>.*?</w:rPr>', run, re.S)
        rpr = rpr_m.group(0) if rpr_m else ""
        if rpr:
            rpr_sup = rpr.replace("</w:rPr>", '<w:vertAlign w:val="superscript"/></w:rPr>')
        else:
            rpr_sup = '<w:rPr><w:vertAlign w:val="superscript"/></w:rPr>'
        rattr = re.match(r'<w:r\b[^>]*>', run).group(0)
        def mk(rpr_x, txt):
            if txt == "":
                return ""
            return f'{rattr}{rpr_x}<w:t xml:space="preserve">{txt}</w:t></w:r>'
        new = mk(rpr, before) + mk(rpr_sup, token) + mk(rpr, after)
        return para_xml[:rm.start()] + new + para_xml[rm.end():]
    raise AssertionError(f"token {token!r} not found in paragraph for {label}")

def para_containing(x, anchor, start=0):
    i = x.find(anchor, start)
    assert i > 0, f"anchor not found: {anchor[:50]!r}"
    s = max(x.rfind('<w:p ', 0, i), x.rfind('<w:p>', 0, i))
    e = x.find('</w:p>', i) + 6
    return s, e

